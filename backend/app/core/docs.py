"""Generated documentation: the capability matrix and the OpenAPI document, from the running app.

Both are produced by building the real application (every plugin that exists) against a throwaway
SQLite database, so the documents describe exactly what this code registers. Used by
``python -m app.cli capabilities`` and ``python -m app.cli openapi``.
"""

from __future__ import annotations

import asyncio
import json
import logging
import tempfile
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from app.core.settings import Settings
from app.core.types import CapabilityStatus

log = logging.getLogger(__name__)

#: Plain-language label per status (CLAUDE.md: working / needs credentials / needs partnership / ...).
STATUS_LABELS: dict[CapabilityStatus, str] = {
    CapabilityStatus.WORKING_NATIVE: "Working (native, on the device)",
    CapabilityStatus.WORKING_LOCAL: "Working (local, on the private backend)",
    CapabilityStatus.WORKING_INTEGRATION: "Working (official integration, credentials present)",
    CapabilityStatus.REQUIRES_CREDENTIALS: "Needs credentials",
    CapabilityStatus.REQUIRES_PARTNERSHIP: "Needs partnership",
    CapabilityStatus.MANUAL_USER_STEP: "Hand-off or manual step",
    CapabilityStatus.RESTRICTED_BY_IOS: "Restricted by iOS",
    CapabilityStatus.UNAVAILABLE: "Unavailable",
}


def _doc_settings(base: Settings, workdir: Path) -> Settings:
    return Settings(
        _env_file=None,
        env="test",
        database_url=f"sqlite+aiosqlite:///{workdir / 'docs.db'}",
        object_dir=workdir / "objects",
        local_dir=workdir / "local",
        config_dir=base.config_dir,
    )


async def _with_app(settings: Settings, plugin_modules: Sequence[str] | None, fn: Any) -> Any:
    from app.main import create_app

    app = create_app(settings, plugin_modules=plugin_modules)
    async with app.router.lifespan_context(app):
        return fn(app)


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def render_capabilities(capabilities: Sequence[Any], tool_count: int) -> str:
    groups: dict[CapabilityStatus, list[Any]] = defaultdict(list)
    for cap in capabilities:
        groups[CapabilityStatus(cap.status)].append(cap)
    lines = [
        "# Integration capability matrix",
        "",
        "Generated by `cd backend && uv run --no-sync python -m app.cli capabilities` from the capability",
        "registry of the running backend (every plugin loaded). Do not edit by hand: regenerate it.",
        "Statuses reflect configuration on the generating machine: with no credentials set, every",
        "integration that needs a key shows as *Needs credentials*. Nothing here checks live connectivity.",
        "",
        f"{len(capabilities)} capabilities, {tool_count} tools.",
        "",
        "| Status | Count |",
        "|---|---|",
    ]
    for status in CapabilityStatus:
        if groups.get(status):
            lines.append(f"| {STATUS_LABELS[status]} | {len(groups[status])} |")
    for status in CapabilityStatus:
        items = sorted(groups.get(status, []), key=lambda c: (c.domain, c.id))
        if not items:
            continue
        lines += [
            "",
            f"## {STATUS_LABELS[status]}",
            "",
            "| Capability | Domain | Title | Integration | Requires | Note |",
        ]
        lines.append("|---|---|---|---|---|---|")
        for cap in items:
            level = cap.integration_level.value if cap.integration_level else ""
            requires = ", ".join(f"`{r}`" for r in cap.requires)
            lines.append(
                f"| `{cap.id}` | {cap.domain} | {_escape(cap.title)} | {level} | {_escape(requires)} | {_escape(cap.note)} |"
            )
    return "\n".join(lines) + "\n"


def capability_markdown(settings: Settings, plugin_modules: Sequence[str] | None = None) -> str:
    with tempfile.TemporaryDirectory(prefix="zoro-docs-") as tmp:
        doc_settings = _doc_settings(settings, Path(tmp))

        def collect(app: Any) -> tuple[list[Any], int]:
            reg = app.state.registry
            return reg.capabilities.all(), len(reg.tools)

        caps, tools = asyncio.run(_with_app(doc_settings, plugin_modules, collect))
    return render_capabilities(caps, tools)


def _openapi_once(settings: Settings, plugin_modules: Sequence[str] | None) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="zoro-docs-") as tmp:
        doc_settings = _doc_settings(settings, Path(tmp))
        document: dict[str, Any] = asyncio.run(
            _with_app(doc_settings, plugin_modules, lambda app: app.openapi())
        )
    return document


def openapi_document(settings: Settings, plugin_modules: Sequence[str] | None = None) -> dict[str, Any]:
    """The OpenAPI document of the app. If one plugin's routes cannot be described (a schema error),
    that plugin is left out and named under ``info.x-zoro-omitted-plugins`` with the error, so the
    document stays truthful instead of failing as a whole."""
    from app.plugins import PLUGIN_MODULES

    modules = tuple(plugin_modules) if plugin_modules is not None else PLUGIN_MODULES
    try:
        return _openapi_once(settings, modules)
    except Exception as exc:  # find the plugin(s) whose routes break schema generation
        log.warning(
            "openapi generation failed; isolating the plugin", extra={"error_type": type(exc).__name__}
        )
    omitted: dict[str, str] = {}
    for module in modules:
        rest = tuple(m for m in modules if m != module)
        try:
            _openapi_once(settings, rest)
        except Exception as exc:  # still failing without this plugin: it is not the (only) cause
            log.debug("plugin not the cause", extra={"plugin": module, "error_type": type(exc).__name__})
            continue
        try:
            _openapi_once(settings, (module,))
        except Exception as exc:
            omitted[module] = f"{type(exc).__name__}: {str(exc).splitlines()[0][:300]}"
    if not omitted:
        raise RuntimeError("OpenAPI generation fails and no single plugin is the cause")
    document = _openapi_once(settings, tuple(m for m in modules if m not in omitted))
    document.setdefault("info", {})["x-zoro-omitted-plugins"] = omitted
    return document


def openapi_json(settings: Settings, plugin_modules: Sequence[str] | None = None) -> str:
    return json.dumps(
        openapi_document(settings, plugin_modules), indent=2, sort_keys=True, ensure_ascii=False
    )
